"""Render each template set's primitives into example.tex, build example.pdf and one preview PNG per primitive."""

from itertools import groupby
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from lib import latex_templates  # noqa: E402 - needs `src` on the path

PREVIEW_WIDTH = 480
PREVIEW_COLORS = 128
# Each group is a \section, a \subsection opens before the primitive named here (id without NN)
SUBSECTIONS = {
    "text/bullets": "Points",
    "text/statement": "Theses",
    "numbers/hero": "Key figures",
    "numbers/keyequation": "Equations",
    "tables/datatable": "Results",
    "tables/decision": "Decisions",
    "figures/fullbleed": "Single figures",
    "figures/chart": "Charts and sets",
    "process/steps": "Steps",
    "process/roadmap": "Timelines",
}


def render_tex(template: latex_templates.TemplateSet) -> tuple[str, dict[Path, int]]:
    r"""Return example.tex, the skeleton's example sections replaced by one section per primitive group, and each primitive's 1-based `\end{frame}` line in it."""
    skeleton = (template.path / "skeleton.tex").read_text()
    start = skeleton.index("\n\\section{") + 1
    end = skeleton.rindex("\\begin{frame}")
    head = skeleton[:start].split("\n", 1)[1]
    parts = ["% Generated by render.py, do not edit\n", head]
    lines = {}
    found = set()
    for _, group in groupby(template.primitives(), key=lambda primitive: primitive.group):
        primitives = list(group)
        parts.append(f"\\section{{{primitives[0].group_label}}}\n")
        for primitive in primitives:
            pid = primitive.id
            path = template.source(pid)
            if pid in SUBSECTIONS:
                found.add(pid)
                parts.append(f"\\subsection{{{SUBSECTIONS[pid]}}}\n")
            text = "\n" + path.read_text() + "\n"
            before = "".join(parts).count("\n")
            lines[path] = before + text[:text.rindex("\\end{frame}")].count("\n") + 1
            parts.append(text)
    missing = set(SUBSECTIONS) - found
    if missing:
        sys.exit(f"{template.name}: SUBSECTIONS names unknown primitives: {', '.join(sorted(missing))}")
    parts.append(skeleton[end:])
    return "".join(parts), lines


def frame_page(work: Path, line: int) -> int:
    """Return the last PDF page SyncTeX puts example.tex's *line* on, the fully revealed overlay of its frame."""
    result = subprocess.run(
        ["synctex", "view", "-i", f"{line}:0:{work / 'example.tex'}", "-o", str(work / "example.pdf")],
        cwd=work, capture_output=True, text=True, check=True,
    )
    pages = [int(entry.split(":", 1)[1]) for entry in result.stdout.splitlines() if entry.startswith("Page:")]
    if not pages:
        sys.exit(f"SyncTeX found no page for line {line} of example.tex")
    return max(pages)


def write_preview(pdf: Path, page: int, target: Path) -> None:
    """Rasterize *page* of *pdf* to the PNG *target*, PREVIEW_WIDTH wide, quantized when ImageMagick is installed."""
    target.parent.mkdir(parents=True, exist_ok=True)
    stem = target.with_suffix("")
    subprocess.run(
        ["pdftoppm", "-png", "-f", str(page), "-l", str(page), "-scale-to-x", str(PREVIEW_WIDTH), "-scale-to-y", "-1",
         "-singlefile", str(pdf), str(stem)],
        check=True,
    )
    if shutil.which("magick"):
        subprocess.run(
            ["magick", str(target), "-strip", "-define", "png:exclude-chunks=date,time", "-colors", str(PREVIEW_COLORS),
             f"PNG8:{target}"],
            check=True,
        )


def write_previews(template: latex_templates.TemplateSet, work: Path, lines: dict[Path, int]) -> None:
    """Write previews/<group>/<NN>-<name>.png for every primitive from its page of the built PDF, remove stale ones."""
    previews = template.path / "previews"
    targets = {latex_templates.preview_path(path): line for path, line in lines.items()}
    for target, line in targets.items():
        write_preview(work / "example.pdf", frame_page(work, line), target)
    for stale in previews.glob("*/*.png"):
        if stale not in targets:
            stale.unlink()
    for folder in previews.glob("*/"):
        if not any(folder.iterdir()):
            folder.rmdir()


def build(template: latex_templates.TemplateSet) -> None:
    """Write example.tex, build example.pdf in a temp dir and write the previews, exit on failure."""
    tex, lines = render_tex(template)
    (template.path / "example.tex").write_text(tex)
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        for sty in template.path.glob("*.sty"):
            shutil.copy(sty, work)
        (work / "example.tex").write_text(tex)
        result = subprocess.run(
            ["latexmk", "-pdf", "-synctex=1", "-interaction=nonstopmode", "example.tex"],
            cwd=work, capture_output=True, text=True,
        )
        if result.returncode != 0:
            log = work / "example.log"
            text = log.read_text(errors="replace") if log.exists() else result.stdout
            sys.exit(f"{template.name}: build failed\n" + "\n".join(text.splitlines()[-40:]))
        shutil.copy(work / "example.pdf", template.path / "example.pdf")
        write_previews(template, work, lines)
    print(f"{template.name}: example.pdf and {len(lines)} previews written")


def main() -> None:
    """Build the named presentation sets or every one."""
    names = sys.argv[1:]
    sets = [template for template in latex_templates.template_sets() if template.is_presentation]
    if names:
        known = {template.name: template for template in sets}
        unknown = [name for name in names if name not in known]
        if unknown:
            sys.exit(f"Unknown template sets: {', '.join(unknown)}")
        sets = [known[name] for name in names]
    for template in sets:
        build(template)


if __name__ == "__main__":
    main()
